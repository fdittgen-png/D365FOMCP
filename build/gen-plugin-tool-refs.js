/**
 * gen-plugin-tool-refs.js — generate the per-service tool reference files for
 * the `d365fo-mcp` Claude Code plugin from the tool registrations themselves.
 *
 *   node build/gen-plugin-tool-refs.js [outDir]
 *
 * Default outDir: plugin/d365fo-mcp/skills/d365fo-mcp-tooling/references
 *
 * The register*Tools() functions are invoked against a capturing mock server
 * and a no-op database stub — handlers are never executed, only the
 * (name, description, inputSchema, annotations) metadata is read. Zod shapes
 * are converted via Zod 4's built-in `z.toJSONSchema`. The output is
 * deterministic so `test/plugin.test.js` can diff it against the committed
 * files and fail when a tool changed without the references being regenerated.
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';

import { registerKbTools } from '../src/azure/kb-tools.js';
import { registerXrefTools } from '../src/azure/xref-tools.js';
import { registerSecTools } from '../src/azure/sec-tools.js';
import { registerTaskRecorderTools } from '../src/azure/taskrecorder-tools.js';
import { registerWikiTools } from '../src/azure/wiki-tools.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DEFAULT_OUT = join(__dirname, '..', 'plugin', 'd365fo-mcp', 'skills', 'd365fo-mcp-tooling', 'references');

/** better-sqlite3 look-alike that never touches disk. Registration-time
 *  probes (e.g. sec-tools' PRAGMA column detection) get empty results. */
const stubDb = {
  prepare: () => ({ all: () => [], get: () => undefined, run: () => ({ changes: 0 }), pluck() { return this; } }),
  pragma: () => [],
  exec: () => {},
};

/** Azure Blob client look-alike for the wiki store — only constructed, never awaited. */
const stubServiceClient = {
  getContainerClient: () => ({ getBlobClient: () => ({}), listBlobsFlat: () => [] }),
};

function captureServer() {
  const tools = [];
  return {
    tools,
    registerTool(name, config) {
      tools.push({ name, description: config.description ?? '', inputSchema: config.inputSchema ?? {}, annotations: config.annotations ?? {}, hasOutputSchema: !!config.outputSchema });
    },
    tool(name, description, schema) { tools.push({ name, description, inputSchema: schema ?? {}, annotations: {}, hasOutputSchema: false }); },
  };
}

/** Render a Zod raw shape ({ field: zodType }) as markdown table rows. */
function paramRows(shape) {
  const keys = Object.keys(shape);
  if (keys.length === 0) return '_No parameters._';
  const json = z.toJSONSchema(z.object(shape), { unrepresentable: 'any', io: 'input' });
  const props = json.properties ?? {};
  const required = new Set(json.required ?? []);
  const rows = keys.map((k) => {
    const p = props[k] ?? {};
    const type = describeType(p);
    const req = required.has(k) ? 'yes' : (p.default !== undefined ? `default \`${JSON.stringify(p.default)}\`` : 'no');
    const desc = String(p.description ?? '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim();
    return `| \`${k}\` | ${type} | ${req} | ${desc} |`;
  });
  return ['| Param | Type | Required | Description |', '|---|---|---|---|', ...rows].join('\n');
}

function describeType(p) {
  if (!p || typeof p !== 'object') return 'any';
  if (p.enum) return p.enum.map((v) => `\`${v}\``).join(' \\| ');
  if (p.anyOf) return p.anyOf.map(describeType).filter((t, i, a) => a.indexOf(t) === i).join(' \\| ');
  let t = Array.isArray(p.type) ? p.type.filter((x) => x !== 'null').join('/') : (p.type ?? 'any');
  if (t === 'array') t = `array<${describeType(p.items)}>`;
  const bounds = [];
  if (p.minimum !== undefined) bounds.push(`≥${p.minimum}`);
  if (p.maximum !== undefined) bounds.push(`≤${p.maximum}`);
  if (p.minLength !== undefined) bounds.push(`min ${p.minLength}`);
  if (p.maxLength !== undefined) bounds.push(`max ${p.maxLength}`);
  return bounds.length ? `${t} (${bounds.join(', ')})` : t;
}

function renderService(svc) {
  const out = [];
  out.push(`# ${svc.title} — tool reference`);
  out.push('');
  out.push(`_Generated by \`npm run gen:plugin-refs\` from \`${svc.source}\`. Do not edit by hand._`);
  out.push('');
  out.push(`MCP server key: \`${svc.key}\` · ${svc.tools.length} tools · all read-only (\`readOnlyHint\`), idempotent, closed-world.`);
  out.push('');
  out.push(svc.intro);
  out.push('');
  out.push('| Tool | One-line purpose |');
  out.push('|---|---|');
  for (const t of svc.tools) out.push(`| \`${t.name}\` | ${firstSentence(t.description)} |`);
  out.push('');
  for (const t of svc.tools) {
    out.push(`## \`${t.name}\``);
    out.push('');
    out.push(t.description.trim());
    out.push('');
    out.push(paramRows(t.inputSchema));
    out.push('');
  }
  return out.join('\n');
}

function firstSentence(d) {
  const s = String(d).replace(/\s+/g, ' ').trim();
  const m = s.match(/^(.{20,180}?[.!?])(\s|$)/);
  return (m ? m[1] : s.slice(0, 160)).replace(/\|/g, '\\|');
}

export function generate() {
  const kb = captureServer(); registerKbTools(kb, stubDb);
  const xref = captureServer(); registerXrefTools(xref, stubDb);
  const sec = captureServer(); registerSecTools(sec, stubDb);
  const tr = captureServer(); registerTaskRecorderTools(tr);
  const wiki = captureServer(); registerWikiTools(wiki, { name: '<wiki>', title: '<Wiki title>', description: '<wiki description>', container: 'wiki', pagesPrefix: '' }, { serviceClient: stubServiceClient });

  const services = [
    { file: 'kb-tools.md', key: 'd365kb', title: 'd365kb — D365FO Knowledge Base', source: 'src/azure/kb-tools.js', tools: kb.tools,
      intro: 'AOT metadata snapshot: tables, fields, indexes, relations, enums, EDTs, classes + method source, data entities, forms, menu items, security objects, labels, and curated anti-hallucination data (traps, AX2012 renames, SQL templates). Use `modules` to scope to custom models; `format: "markdown"` only for human-facing prose.' },
    { file: 'xref-tools.md', key: 'd365xref', title: 'd365xref — D365FO Cross-References', source: 'src/azure/xref-tools.js', tools: xref.tools,
      intro: 'Compiler cross-reference snapshot: who calls, reads, writes, extends, implements or references what. Start with `xref_object_summary` for counts, then drill. Coverage = compiled models in the snapshot (Microsoft + listed ISV/custom models); `xref_list_modules` shows exactly which.' },
    { file: 'sec-tools.md', key: 'd365sec', title: 'd365sec — D365FO Security Model', source: 'src/azure/sec-tools.js', tools: sec.tools,
      intro: 'Security configuration snapshot (AOT roles/duties/privileges + user/role assignments from DMF): resolution role → sub-role → duty → privilege → entry point with Deny-wins. Permission cells render ✓ Grant / ✗ Deny / — None. User data is internal-staff information — keep it inside the analysis.' },
    { file: 'taskrecorder-tools.md', key: 'd365taskrecorder', title: 'd365taskrecorder — Task Recorder converter', source: 'src/azure/taskrecorder-tools.js', tools: tr.tools,
      intro: 'Stateless converters for Task Recorder output: `.axtr` (server recording) to structured Markdown, or recording + client reproReport/DOCX screenshots to an enriched, self-contained MHTML document with KB technical detail and role-based security — optionally with a contract XML validated against `schemas/task-recording-document.xsd`.' },
    { file: 'wiki-tools.md', key: 'wiki-<name>', title: 'wiki-* — blob-backed wiki MCPs', source: 'src/azure/wiki-tools.js', tools: wiki.tools,
      intro: 'One MCP server per wiki (support tickets, runbooks, decisions). The same four tools exist on every wiki server; the server name identifies the wiki. `wiki_index` once per session, `wiki_search` to find, `wiki_read` to load a page by slug.' },
  ];
  return services.map((s) => ({ file: s.file, content: renderService(s) + '\n' }));
}

// CLI entry
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const outDir = process.argv[2] || DEFAULT_OUT;
  mkdirSync(outDir, { recursive: true });
  for (const { file, content } of generate()) {
    writeFileSync(join(outDir, file), content);
    console.log(`wrote ${join(outDir, file)} (${content.length} bytes)`);
  }
}
